/**
 * Data Integrity Validator
 * Runs at startup or within tests to verify the integrity of the canonical dataset.
 */
export function validateTraditionalDatasetIntegrity(): { isValid: boolean; errors: string[] } {
  const errors: string[] = [];

  // 1. Must contain exactly 25 records
  if (TRADITIONAL_REFERENCES.length !== 25) {
    errors.push(`Expected 25 canonical records, found ${TRADITIONAL_REFERENCES.length}`);
  }

  const seenIds = new Set<string>();
  const seenValues = new Set<number>();

  for (const record of TRADITIONAL_REFERENCES) {
    // 2. Unique ID
    if (seenIds.has(record.id)) {
      errors.push(`Duplicate record ID found: ${record.id}`);
    }
    seenIds.add(record.id);

    // 3. Unique numeric value
    if (seenValues.has(record.numericValue)) {
      errors.push(`Duplicate numeric value found: ${record.numericValue}`);
    }
    seenValues.add(record.numericValue);

    // 4. Numeric value range [4.0, 10.0]
    if (record.numericValue < 4.0 || record.numericValue > 10.0) {
      errors.push(`Record ${record.id} value ${record.numericValue} is out of expected [4.0, 10.0] range`);
    }

    // 5. Unit must be virarkadai
    if (record.unit !== 'virarkadai') {
      errors.push(`Record ${record.id} has invalid unit: ${record.unit}`);
    }

    // 6. Must have Tamil description
    if (!record.tamilDescription || record.tamilDescription.trim().length === 0) {
      errors.push(`Record ${record.id} is missing Tamil description`);
    }

    // 7. Must have display label
    if (!record.displayLabel) {
      errors.push(`Record ${record.id} is missing display label`);
    }
  }

  // 8. Check that all values from 4.00 to 10.00 in 0.25 steps exist
  for (let v = 4.0; v <= 10.0; v += 0.25) {
    const rounded = Math.round(v * 100) / 100;
    if (!seenValues.has(rounded)) {
      errors.push(`Missing expected traditional value: ${rounded}`);
    }
  }

  return {
    isValid: errors.length === 0,
    errors
  };
}
